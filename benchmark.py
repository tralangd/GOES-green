#!/usr/bin/env python3

import argparse
import csv
import numpy as np
import os

from PIL import Image
import pillow_jxl
Image.MAX_IMAGE_PIXELS = 500000000 # increase default limit


def benchmark():

    # read in LUT
    LUT = np.fromfile("data/LUT.bin", dtype=np.uint8).reshape(256,256,256)

    # if all.txt does not exist, create it
    os.makedirs(os.path.dirname("data/results.csv"), exist_ok=True)
    if not os.path.exists("data/results.csv"):
        with open("data/results.csv", mode='w', newline='', encoding='utf-8') as file:
            writer = csv.DictWriter(file, fieldnames=["timestamp","TrueColor","LUT"])
            writer.writeheader()

    # open data/results.csv and read all processed timestamps
    with open("data/results.csv", mode='r', newline='', encoding='utf-8') as file:
        reader = csv.DictReader(file)
        timestamps_done = []
        for row in reader:
            timestamps_done.append(row['timestamp'])

    # create list of new timestamps
    timestamps = os.listdir("data/JXL")
    timestamps_new = []
    for timestamp in timestamps:

        # if the "timestamp" actually a file instead of a directory, skip it
        if not os.path.isdir(f"data/JXL/{timestamp}"):
            continue

        # if timestamp is not in the 'done' list then it needs to be processed
        if timestamp not in timestamps_done:
            timestamps_new.append(timestamp)

    # process all new timestamps
    for timestamp in timestamps_new:

        B = Image.open(f"data/JXL/{timestamp}/HIMAWARI-8_AHI_B01_{timestamp}_FLDK.jxl")
        G = Image.open(f"data/JXL/{timestamp}/HIMAWARI-8_AHI_B02_{timestamp}_FLDK.jxl")
        R = Image.open(f"data/JXL/{timestamp}/HIMAWARI-8_AHI_B03_{timestamp}_FLDK.jxl")
        V = Image.open(f"data/JXL/{timestamp}/HIMAWARI-8_AHI_B04_{timestamp}_FLDK.jxl")

        # check that images are grayscale and without alpha
        if len(B.getbands()) != 1 or len(B.getbands()) != 1 or len(B.getbands()) != 1 or len(B.getbands()) != 1:
            raise ValueError("Unexpected iamge depth. Was expecting single channel (grayscale and without alpha)")
        # check that all iamges are 11000 x 11000
        if B.size != (11000,11000) or G.size != (11000,11000) or R.size != (11000,11000) or V.size != (11000,11000):
            raise ValueError("Unexpected iamge size. Was expecting 11000 x 11000 pixels.")
        
        print(f"Benchmarking timestamp {timestamp}")
        
        # convert Imgages to numpy arrays
        B = np.array(B,dtype='uint8')
        G = np.array(G,dtype='uint8')
        R = np.array(R,dtype='uint8')
        V = np.array(V,dtype='uint8')

        # TrueColor Synthetic Green
        G_tc = np.uint8( 0.45*B + 0.45*R + 0.10*V )
        RMSE_tc = np.sqrt( np.sum( np.square( np.float32(G) - np.float32(G_tc) ) ) / (11000*11000) )
        PSNR_tc = 20 * np.log10(255 / RMSE_tc)

        # LUT Synthetic Green
        G_lut = np.uint8( LUT[B,R,V] )
        RMSE_lut = np.sqrt( np.sum( np.square( np.float32(G) - np.float32(G_lut) ) ) / (11000*11000) )
        PSNR_lut = 20 * np.log10(255 / RMSE_lut)

        # append results to file
        with open("data/results.csv", mode='a', newline='', encoding='utf-8') as file:
            writer = csv.DictWriter(file, fieldnames=["timestamp","TrueColor","LUT"])
            writer.writerow({'timestamp': timestamp, 'TrueColor': PSNR_tc, 'LUT': PSNR_lut})

    # read all PSNR values for both methods
    PSNR_string_tc = []
    PSNR_string_lut = []
    with open('data/results.csv', mode='r', newline='', encoding='utf-8') as file:
        reader = csv.DictReader(file)
        for row in reader:
            PSNR_string_tc.append(row['TrueColor'])
            PSNR_string_lut.append(row['LUT'])
    PSNR_float_tc = [float(str) for str in PSNR_string_tc]
    PSNR_float_lut = [float(str) for str in PSNR_string_lut]

    # report average PSNR for both methods
    print("Average PSNR for CIMSS TrueColor Synthetic Green is:", round(sum(PSNR_float_tc)/len(PSNR_float_tc),2))
    print("Average PSNR for Custom Color Lookup Table Green is:", round(sum(PSNR_float_lut)/len(PSNR_float_lut),2))
    print("Higher PSNR is better")


if __name__ == "__main__":

    parser = argparse.ArgumentParser(description="Compare PSNR of synthetic green channels generated by LUT and TrueColor methods. This function does not take any arguments.")
    
    args = parser.parse_args()

    benchmark()
    